"""Write outputs/tables/Stage_4_Reliability_Robustness_Report.md from saved files."""
from __future__ import annotations

import pandas as pd

from . import config

T = config.TABLE_DIR


def block(df, n=None):
    if n is not None:
        df = df.head(n)
    return "```\n" + df.to_string(index=False) + "\n```\n"


def main() -> None:
    cand = pd.read_csv(T / "pressure_thresholds_candidates.csv")
    cand_sh = pd.read_csv(T / "innings1_model_pressure_shares_pooled.csv")
    thr = pd.read_csv(T / "pressure_thresholds.csv")
    early = pd.read_csv(T / "early_ball_diagnostics.csv")
    chase = pd.read_csv(T / "early_chase_diagnostics.csv")
    over = pd.read_csv(T / "li_calibration_by_over.csv")
    stab = pd.read_csv(T / "early_feature_stability.csv")
    trim_corr = pd.read_csv(T / "B_vs_B_trim_correlations.csv")
    trim_ov = pd.read_csv(T / "B_vs_B_trim_top15_overlap.csv")
    topb = pd.read_csv(T / "top15_batters_B_trim.csv")
    topw = pd.read_csv(T / "top15_bowlers_B_trim.csv")
    splits = pd.read_csv(T / "reliability_match_splits.csv")
    rel = pd.read_csv(T / "reliability_correlations.csv")
    reltop = pd.read_csv(T / "reliability_top15_overlap.csv")
    alpha = pd.read_csv(T / "ridge_alpha_sensitivity.csv")
    alpha_ov = pd.read_csv(T / "ridge_alpha_top15_overlap.csv")
    iplc = pd.read_csv(T / "ipl_vs_combined_correlations.csv")
    expo = pd.read_csv(T / "combined_top15_competition_exposure.csv")

    split_lines = []
    for col in ("scheme1", "scheme2"):
        for side in splits[col].unique():
            s = splits[splits[col] == side]
            split_lines.append(f"- {col} {side}: {len(s)} matches, {s.match_date.min()} to {s.match_date.max()}")
    split_text = "\n".join(split_lines)

    text = f"""# Stage 4: Reliability and Robustness Report

Generated by `py -m src.step4_report` from saved outputs. Variant B and all
frozen Step 1-3 files are unchanged; B_trim and the diagnostics are new.

## 1. Corrected pooled-threshold diagnostics

The previous `innings1_model_pressure_shares.csv` mixed a within-innings
quartile in innings 1 with the pooled threshold in innings 2. It is retained
unchanged as a historical file and is not a valid Variant B comparison. The
corrected files are `pressure_thresholds_candidates.csv` and
`innings1_model_pressure_shares_pooled.csv`.

Existing thresholds:

{block(thr)}

Candidate pooled thresholds (one q75 over both innings):

{block(cand)}

Corrected HIGH counts by innings and phase:

{block(cand_sh)}

## 2. Frozen Variant B

Frozen `pressure_ball.parquet`: 183,167 deliveries; 45,792 HIGH;
25.0001% (45,792 / 183,167); threshold 1.0871463111; zero exact ties.
The logistic-candidate recomputation reproduces every phase count exactly.

## 3. Legal-ball indexing

`legal_ball_pos = legal_balls_before + 1` for every delivery, computed per
match and innings. Legal deliveries advance the count; wides and no-balls do
not, so an illegal delivery is attributed to the next legal-ball position.
Positions 1-36 are reported; missing positions are not filled.

## 4. Early-ball diagnostics

Innings 1:

{block(early[early.innings == 1], 12)}

Innings 2:

{block(early[early.innings == 2], 12)}

Chase balls 1-12:

{block(chase)}

LI calibration by over (innings 1):

{block(over[over.innings == 1])}

Early feature stability (legal balls 1-12):

{block(stab)}

**Interpretation:** over-1 LI is a genuine early-leverage effect - mean |WPA| is
also highest in over 1 (0.0192 in innings 1, 0.0517 in chases) and LI tracks
|WPA| across overs - but its ball-1 magnitude is amplified by unstable early
state features (CRR is 0 at the first ball and then jumps to 6.80, and RRR is
missing on 50.1% of first-12-ball rows because they are innings 1).

## 5. B_trim

B_trim is identical to B except that all deliveries with `legal_ball_pos <= 12`
(including wides and no-balls before the 12th legal ball) get zero pressure and
zero ordinary weight. Original B weights are untouched.

Validation: 183,167 rows; 19,311 early rows; 0 early rows with non-zero pressure
weight; 0 late rows whose weight differs from B.

Ridge alpha is fixed at 10,000 (not retuned). No bootstrap: RR intervals are
`NOT DONE - bootstrap not requested for B_trim`.

Top 15 batters:

{block(topb[["player_name", "n_eff", "pressure_balls", "matches", "apv", "apv_ordinary", "rr", "con_positive_share", "con_median", "con_mad"]])}

Top 15 bowlers:

{block(topw[["player_name", "n_eff", "pressure_balls", "matches", "apv", "apv_ordinary", "rr", "con_positive_share", "con_median", "con_mad"]])}

B vs B_trim:

{block(trim_corr)}

{block(trim_ov)}

CON rules unchanged: batter unit = innings, bowler unit = spell per match,
minimum 6 pressure-weighted balls; share = fraction with positive weighted
WPAE; median/MAD over qualifying per-match pressure values.

## 6. Reliability splits

{split_text}

Odd/even and earlier/later halves are disjoint and exhaustive; ordering is by
match date then match_id.

Correlations across halves (n_eff >= 50 in both halves):

{block(rel)}

Top-15 overlap:

{block(reltop)}

**Interpretation:** CON share and CON median are the only metrics with
consistently positive (though weak, roughly 0.10-0.30) cross-half correlations,
while raw APV is weakly positive only in the earlier/later split. Ridge APV and
ridge RR are essentially uncorrelated across halves (Spearman about -0.02 to
0.10) with top-15 overlaps of only 1-4 of 15, so the Stage 4 APV rankings do not
persist across independent match samples and should not be read as reliable
player rankings.

## 7. Alpha sensitivity (Variant B)

{block(alpha)}

{block(alpha_ov)}

Rankings are stable to alpha (Spearman >= 0.958) with 13-14 of 15 top players
shared; this is robustness to regularisation, not evidence of player-level
reliability.

## 8. IPL-only versus combined

{block(iplc)}

Competition exposure of the combined B top 15:

{block(expo)}

## 9. Limitations and NOT DONE

- B_trim bootstrap confidence intervals: NOT DONE - bootstrap not requested.
- The exact command that produced the earlier innings-1 LightGBM file remains
  NOT DONE (no Git history).
- Adjusted-APV versus old simple-mean APV correlation: NOT DONE - the old file
  uses a different frozen delivery universe.
- Reliability correlations are small by construction because per-ball WPAE is
  very noisy; n_eff >= 50 is a reliability screen, not evidence of precision.
- No Stage 5 shrinkage and no Stage 6 ranking were performed.
"""
    (T / "Stage_4_Reliability_Robustness_Report.md").write_text(text, encoding="utf-8")
    print("WROTE", T / "Stage_4_Reliability_Robustness_Report.md")


if __name__ == "__main__":
    main()
