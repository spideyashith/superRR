"""Write the Step 5 report and the split-half covariance cross-check."""
from __future__ import annotations

import numpy as np
import pandas as pd

from . import config

T = config.TABLE_DIR


def block(df, n=None):
    if n is not None:
        df = df.head(n)
    return "```\n" + df.to_string(index=False) + "\n```\n"


def player_raw(df, kind, ids):
    """Raw pressure-weighted mean and n_eff per player inside a match set."""
    idcol = "striker_id" if kind == "batter" else "bowler_id"
    valcol = "y_bat" if kind == "batter" else "y_bowler"
    sub = df[df.match_id.isin(ids)]
    w = sub["pressure_weight_B_trim"].to_numpy(float)
    d = pd.DataFrame({"pid": sub[idcol].to_numpy(), "w": w,
                      "wy": w * sub[valcol].to_numpy(float)})
    g = d.groupby("pid").agg(sw=("w", "sum"), swy=("wy", "sum"),
                             sw2=("w", lambda x: float(np.sum(x ** 2))))
    g = g[g.sw > 0]
    g["raw_apv"] = g.swy / g.sw
    g["n_eff"] = g.sw ** 2 / g.sw2
    return g[["raw_apv", "n_eff"]]


def covariance_table() -> pd.DataFrame:
    from .step4_stage4 import attach_trim
    df = pd.read_parquet(T / "ball_values.parquet")
    df = attach_trim(df, pd.read_parquet(T / "variant_weights_B_trim.parquet"))
    df["match_id"] = df["match_id"].astype("int64")
    sp = pd.read_csv(T / "reliability_match_splits.csv")
    rows = []
    for kind in ("batter", "bowler"):
        for scheme, col in (("odd_even", "scheme1"), ("early_late", "scheme2")):
            halves = list(pd.unique(sp[col]))
            a = player_raw(df, kind, sp.loc[sp[col] == halves[0], "match_id"])
            b = player_raw(df, kind, sp.loc[sp[col] == halves[1], "match_id"])
            common = [p for p in set(a.index) & set(b.index)
                      if a.loc[p, "n_eff"] >= 50 and b.loc[p, "n_eff"] >= 50]
            cov = float(np.cov(a.loc[common, "raw_apv"], b.loc[common, "raw_apv"], ddof=1)[0, 1])
            rows.append({"player_type": kind, "scheme": scheme,
                         "half_1": halves[0], "half_2": halves[1],
                         "n_players": len(common), "cov_raw_apv": cov})
    return pd.DataFrame(rows)


def main() -> None:
    cov = covariance_table()
    cov.to_csv(T / "step5_split_half_covariance.csv", index=False)

    pv = pd.read_csv(T / "step5_predictive_validity.csv")
    sig = pd.read_csv(T / "step5_signal_variance.csv")
    choice = pd.read_csv(T / "step5_variant_choice.csv")
    elig = pd.read_csv(T / "step5_shrinkage_eligible.csv")
    allp = pd.read_csv(T / "step5_shrinkage_all_players.csv")

    text = f"""# Stage 5: Predictive Validity and Shrinkage

Generated by `py -m src.step5_report` from saved outputs. Variant B and all
frozen Step 1-4 files are unchanged.

## 1. Design

B_trim and B are analysed separately. Halves are the Step 4 splits (odd/even
and early/late by match date, then match_id). Every predictor is estimated
inside the source half only: three ridge fits at alpha = 10,000 (pressure
weights, ordinary weights, weight = 1 on every ball) plus the raw
pressure-weighted mean and the CON metrics. The target is the target half's
LI-weighted raw mean of y or its CON median. Players need n_eff >= 50 in both
halves. `blend` is the mean of the source-half z-scores of ridge ordinary APV,
CON share and CON median (players missing any component get NaN).

## 2. Predictive validity, target = raw pressure mean

{block(pv[pv.target == "raw_apv"])}

## 3. Predictive validity, target = CON median

{block(pv[pv.target == "con_median"])}

**Which predictors carry signal (two sentences):** Raw pressure mean and
CON share/median carry the only consistent signal for batters (mean Spearman
about 0.10-0.15 against raw pressure value and 0.18-0.22 against CON median),
with the all-ball ridge and the blend close behind, while ridge pressure APV
is near zero. For bowlers the ridge predictors are consistently negative
(about -0.03 to -0.20 against raw value) and only CON share and CON median
retain a weak positive relation to the CON median target, so no ridge-based
predictor should be used as a forward-looking skill measure.

## 4. Signal variance and shrinkage (B_trim, raw pressure mean)

`se_i^2 = sum(w^2 (y - mean_w)^2) / (sum w)^2`, where `mean_w = sum(w y) / sum(w)`.
Signal variance = max(0, var(observed means, ddof=1) - mean(se_i^2)); 95% CI
from 1,000 bootstrap resamples over players, flooring each replicate at 0.
Shrinkage factor `B_i = signal_var / (signal_var + se_i^2)`; shrunk value
`mu + B_i (mean_i - mu)` with mu the n_eff-weighted mean of the player means.

{block(sig)}

Shrinkage factor range:

{block(sig[["player_type", "n_players", "shrink_min", "shrink_median", "shrink_max"]])}

Split-half covariance cross-check (B_trim raw pressure mean, players with
n_eff >= 50 in both halves):

{block(cov)}

The method-of-moments signal variance is positive (batters 0.000571, CI
0.000292-0.000893; bowlers 0.000146, CI 0.000004-0.000382), but the split-half
covariances are an order of magnitude smaller and negative for bowlers
(-0.000007 and -0.000003), so the signal variance is only weakly identified
and is not corroborated by the split-half check. Shrinkage is therefore
reported as a sensitivity device, not as a validated precision-weighting.

Eligible shrunk values saved: {len(elig)} players (n_eff >= 150 and >= 15
matches); all players saved separately ({len(allp)} rows).

## 5. Variant choice

Rule fixed in advance: higher mean split-half Spearman across all metrics in
`reliability_correlations.csv`, separately per role; ties go to B_trim.

{block(choice)}

## 6. Limitations

- Predictive correlations are small; with roughly 125-203 players per cell a
  Spearman of 0.15 is not statistically strong evidence of forward skill.
- The bootstrap CI covers players, not matches; it does not account for
  within-player match clustering.
- `blend` uses in-half z-scores, so it is comparable only within a half.
- No Stage 6 ranking was produced.
"""
    (T / "Stage_5_Predictive_Validity_and_Shrinkage_Report.md").write_text(text, encoding="utf-8")
    print("WROTE report")
    print(cov.to_string(index=False))


if __name__ == "__main__":
    main()
