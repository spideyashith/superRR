"""Stage 0: data audit.

Generates ``outputs/tables/data_audit.md`` from the raw pack and prints a
summary. Every number in the artefact is computed here; none is hand-written.

Run from the project root::

    py -m src.audit
"""
from __future__ import annotations

import sys

import numpy as np
import pandas as pd

from . import config
from .load_clean import (
    SCHEMA_MAP,
    check_score_reconstruction,
    innings_summary,
    load_clean,
)

pd.set_option("display.width", 200)


# ---------------------------------------------------------------------------
# Small markdown helpers
# ---------------------------------------------------------------------------
def _fmt_int(value: float) -> str:
    if pd.isna(value):
        return "-"
    return f"{int(value):,}"


def _fmt_pct(value: float) -> str:
    if pd.isna(value):
        return "-"
    return f"{value:.2f}%"


def _fmt_float(value: float, digits: int = 2) -> str:
    if pd.isna(value):
        return "-"
    return f"{value:.{digits}f}"


def _md_table(headers: list[str], rows: list[list[object]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    for row in rows:
        out.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(out)


def _profile_table(df: pd.DataFrame, raw: pd.DataFrame) -> str:
    """dtype, nulls and cardinality for every column of one file."""
    rows = []
    for col in df.columns:
        total = len(df)
        nulls = int(raw[col].isna().sum()) if col in raw.columns else int(df[col].isna().sum())
        rows.append(
            [
                f"`{col}`",
                str(df[col].dtype),
                _fmt_int(nulls),
                _fmt_pct(100 * nulls / total if total else np.nan),
                _fmt_int(df[col].nunique(dropna=True)),
            ]
        )
    return _md_table(["column", "dtype after load", "nulls", "null rate", "unique"], rows)


# ---------------------------------------------------------------------------
# Audit
# ---------------------------------------------------------------------------
def main() -> None:
    data = load_clean()
    raw = data["raw"]
    bbb = data["bbb"]
    matches = data["matches"]
    players = data["players"]
    pe = data["playing_eleven"]
    mapping = data["mapping"]
    comps = data["competitions"]
    teams = data["teams"]

    lines: list[str] = []
    add = lines.append

    # ------------------------------------------------------------------
    # Header
    # ------------------------------------------------------------------
    add("# Stage 0 data audit: SupeRR Selector Season 2")
    add("")
    add(
        "Generated by `py -m src.audit`. All figures below are computed from "
        "`Data Pack/` at run time. The audit covers the six CSV files; the "
        "Round 1 problem statement PDF was read separately and adds no data "
        "fields beyond the PRD."
    )
    add("")
    add("Data pack ignored paths: `__MACOSX/`, `._*`, `.DS_Store`.")
    add("")

    # ------------------------------------------------------------------
    # 1. Files
    # ------------------------------------------------------------------
    add("## 1. Files loaded")
    add("")
    rows = []
    for name in ["ball_by_ball", "matches", "teams", "competitions", "playing_eleven", "competition_team_player_mapping"]:
        df = raw[name]
        rows.append([f"`{name}.csv`", _fmt_int(len(df)), _fmt_int(df.shape[1])])
    add(_md_table(["file", "rows", "columns"], rows))
    add("")
    n_comps_with_balls = int(
        matches.loc[matches["match_id"].isin(bbb["match_id"]), "comp_id"].nunique()
    )
    add(
        f"`ball_by_ball.csv` is the fact table: {_fmt_int(len(bbb))} deliveries "
        f"across {_fmt_int(bbb['match_id'].nunique())} matches, "
        f"{_fmt_int(matches['venue_id'].nunique())} venues, "
        f"{_fmt_int(n_comps_with_balls)} competitions, "
        f"{_fmt_int(bbb['striker_id'].nunique())} batters and "
        f"{_fmt_int(bbb['bowler_id'].nunique())} bowlers."
    )
    add("")

    # ------------------------------------------------------------------
    # 2. Schema map
    # ------------------------------------------------------------------
    add("## 2. Schema map: PRD field to real column")
    add("")
    add(
        "Column names were inspected, not assumed. `runs` is **runs off the bat**; "
        "total runs on a delivery is `runs + extras1_runs + extras_2_runs`."
    )
    add("")
    add(
        _md_table(
            ["PRD field", "source column(s)", "note"],
            [[f"**{r['field']}**", f"`{r['source']}`", r["note"]] for r in SCHEMA_MAP],
        )
    )
    add("")

    # ------------------------------------------------------------------
    # 3. Column profiles / null rates
    # ------------------------------------------------------------------
    add("## 3. Column profiles and null rates")
    add("")
    add(
        "CSVs are read as strings (IDs preserved exactly) and then converted to the "
        "dtypes shown. Null counts are from the raw file. `extras_type` uses the literal "
        "string `None` for 'no extras'; it is normalised to `none` in the cleaned table."
    )
    add("")
    profiles = [
        ("ball_by_ball", "ball_by_ball", bbb),
        ("matches", "matches", matches),
        ("playing_eleven", "playing_eleven", raw["playing_eleven"]),
        ("competition_team_player_mapping", "competition_team_player_mapping", raw["competition_team_player_mapping"]),
        ("competitions", "competitions", raw["competitions"]),
        ("teams", "teams", raw["teams"]),
    ]
    for raw_name, label, frame in profiles:
        add(f"### `{label}.csv`")
        add("")
        add(_profile_table(frame, raw[raw_name]))
        add("")

    # ------------------------------------------------------------------
    # 4. Key relationships
    # ------------------------------------------------------------------
    bbb_pids = set(bbb["striker_id"]) | set(bbb["bowler_id"]) | set(bbb["non_striker_id"])
    map_pids = set(mapping["player_id"])
    xi_pids = set(pe["player_id"])
    bbb_teams = set(bbb["batting_team_id"]) | set(bbb["bowling_team_id"])
    match_teams = set(matches["home_team_id"]) | set(matches["away_team_id"])
    missing_xi = sorted((bbb_pids | set()) - xi_pids)

    add("## 4. Key relationships and integrity")
    add("")
    rows = [
        ["match_id", "ball_by_ball to matches", _fmt_int(bbb["match_id"].nunique()), _fmt_int(matches["match_id"].nunique()), f"{_fmt_int(len(set(matches['match_id']) - set(bbb['match_id'])))} matches have no deliveries"],
        ["player_id", "ball_by_ball to player registry", _fmt_int(len(bbb_pids)), _fmt_int(len(map_pids)), f"{_fmt_int(len(bbb_pids - map_pids))} missing from registry"],
        ["player_id", "playing_eleven to player registry", _fmt_int(len(xi_pids)), _fmt_int(len(map_pids)), f"{_fmt_int(len(xi_pids - map_pids))} missing from registry"],
        ["team_id", "ball_by_ball to matches", _fmt_int(len(bbb_teams)), _fmt_int(len(match_teams)), f"{_fmt_int(len(bbb_teams - match_teams))} unmatched"],
        ["comp_id", "matches to competitions", _fmt_int(matches["comp_id"].nunique()), _fmt_int(comps["comp_id"].nunique()), "all match competitions found"],
        ["venue_id", "matches only", _fmt_int(matches["venue_id"].nunique()), "-", "no venue dimension table"],
    ]
    add(_md_table(["key", "relationship", "in child", "in parent", "result"], rows))
    add("")
    add(
        f"Two players in the ball-by-ball file are absent from `playing_eleven`: "
        f"`{', '.join(missing_xi)}` (Syed Haider and Basil Hameed, both UAE in the "
        "non-IPL Emerging Teams Asia Cup). This is one more reason that competition "
        "is flagged out of scope."
    )
    add("")

    # ------------------------------------------------------------------
    # 5. Match universe and exclusions
    # ------------------------------------------------------------------
    add("## 5. Match universe and exclusions")
    add("")
    add(
        "Scope follows the PRD: IPL and T20I from 2022 onward. The pack also contains "
        "two domestic-development T20 competitions (Competition IDs 2670 and 3289, "
        "'Mens T20 Emerging Teams Asia Cup 2024' and 'Asia Cup Rising Stars 2025'). "
        "They are neither IPL nor T20I and are excluded by default."
    )
    add("")

    rows = []
    for season, group in matches[matches["is_ipl"]].groupby("season"):
        rows.append([f"IPL {season}", "T20", "IPL", _fmt_int(len(group))])
    t20i = matches[matches["is_t20i"]]
    rows.append([f"T20I series ({t20i['comp_id'].nunique()} competitions)", "T20I", "T20I", _fmt_int(len(t20i))])
    other = matches[~matches["in_scope"]]
    for comp_name, group in other.groupby("comp_name"):
        rows.append([comp_name, group["match_format"].iloc[0], "excluded", _fmt_int(len(group))])
    add(_md_table(["competition", "format", "scope", "matches"], rows))
    add("")

    excl = (
        matches.groupby(["in_scope", "exclusion_reason"]).size().reset_index(name="matches")
        .sort_values(["in_scope", "matches"], ascending=[False, False])
    )
    rows = []
    for _, r in excl.iterrows():
        rows.append(["yes" if r["in_scope"] else "no", r["exclusion_reason"] or "(kept)", _fmt_int(r["matches"])])
    add(_md_table(["in scope", "exclusion reason", "matches"], rows))
    add("")
    add(
        f"Total matches in `matches.csv`: **{_fmt_int(len(matches))}**. "
        f"In scope: **{_fmt_int(int(matches['in_scope'].sum()))}**. "
        f"Analysis-ready after excluding no-result/abandoned, tied/super-over, "
        f"DLS/shortened and incompletely recorded matches: "
        f"**{_fmt_int(int(matches['analysis_ready'].sum()))}**."
    )
    add("")
    ready = matches[matches["analysis_ready"]]
    add(
        f"Analysis-ready split: **{_fmt_int(int(ready['is_ipl'].sum()))} IPL** and "
        f"**{_fmt_int(int((~ready['is_ipl']).sum()))} T20I** matches; "
        f"{_fmt_int(int(bbb.loc[bbb['match_id'].isin(ready['match_id']), 'match_id'].nunique()))} "
        "matches have delivery data. "
        f"**{_fmt_int(int(bbb['delivery_in_analysis'].sum()))}** of "
        f"{_fmt_int(len(bbb))} deliveries carry the `delivery_in_analysis` flag."
    )
    add("")

    # ------------------------------------------------------------------
    # 6. Delivery composition
    # ------------------------------------------------------------------
    add("## 6. Delivery composition and extras attribution")
    add("")
    ex = bbb.groupby("extras_type", as_index=False).agg(
        deliveries=("match_id", "size"),
        runs=("extra_runs", "sum"),
    )
    ex["share"] = 100 * ex["deliveries"] / len(bbb)
    ex = ex.sort_values("deliveries", ascending=False)
    rows = [
        [
            f"`{r['extras_type']}`" if r["extras_type"] != "none" else "`none`",
            _fmt_int(r["deliveries"]),
            _fmt_pct(r["share"]),
            _fmt_int(r["runs"]),
        ]
        for _, r in ex.iterrows()
    ]
    add(_md_table(["extras_type", "deliveries", "share of deliveries", "extras runs"], rows))
    add("")
    untyped_extra = int(((bbb["extras_type"] == "none") & (bbb["extra_runs"] > 0)).sum())
    add(
        f"Legal deliveries: **{_fmt_int(int(bbb['is_legal'].sum()))}** of "
        f"{_fmt_int(len(bbb))} ({_fmt_pct(100 * bbb['is_legal'].mean())}). "
        f"Wides: **{_fmt_int(int(bbb['is_wide'].sum()))}**, no-balls "
        f"(`Overstep` + `other`): **{_fmt_int(int(bbb['is_noball'].sum()))}**, "
        f"penalty rows: **{_fmt_int(int(bbb['is_penalty'].sum()))}**. "
        "Wides and no-balls are charged to the bowler; byes and leg-byes are not. "
        "A wide is not a ball faced; a no-ball is faced but is not a legal ball."
    )
    add("")
    add(
        f"{_fmt_int(untyped_extra)} deliveries have no `extras_type` but a non-zero extra run; "
        "they are treated as legal deliveries and the extra is charged to the team, "
        "not the bowler. Total runs are unaffected."
    )
    add("")

    # ------------------------------------------------------------------
    # 7. Data-quality checks
    # ------------------------------------------------------------------
    add("## 7. Data-quality checks")
    add("")
    dupes = int(raw["ball_by_ball"].duplicated().sum())
    key_dupes = int(raw["ball_by_ball"].duplicated(["match_id", "innings", "innings_ball_num"]).sum())
    xi_dupes = int(pe.duplicated(["match_id", "player_id"]).sum())
    inn = innings_summary(bbb)
    checks = check_score_reconstruction(bbb, matches)

    rows = [
        ["Duplicate delivery rows", _fmt_int(dupes), "none"],
        ["Duplicate (match, innings, delivery number)", _fmt_int(key_dupes), "none"],
        ["Duplicate (match, player) in playing_eleven", _fmt_int(xi_dupes), "3 matches; all tied/super-over or eliminator matches, excluded"],
        ["Innings with more than 120 legal balls", _fmt_int(int((inn["legal_balls"] > config.REGULATION_BALLS).sum())), "none"],
        ["Innings with more than 10 wickets", _fmt_int(int((inn["wickets"] > 10).sum())), "none"],
        ["Runs-win margins checked", _fmt_int(int(checks["stated_margin"].notna().sum())), "reconstructed from ball-by-ball"],
        ["Runs-win margin mismatches", _fmt_int(int((~checks["margin_ok"]).sum())), "none in analysis-ready set"],
        ["Wicket-win target checks failed", _fmt_int(int((~checks["target_ok"]).sum())), "chasing side must reach target"],
        ["Legal-ball checks failed", _fmt_int(int((~checks["balls_ok"]).sum())), "none"],
        ["Wicket checks failed", _fmt_int(int((~checks["wickets_ok"]).sum())), "none"],
        ["Matches with a truncated innings", _fmt_int(int(matches["is_incomplete_innings"].sum())), "ended without using all balls, all out, or reaching target"],
    ]
    add(_md_table(["check", "count", "interpretation"], rows))
    add("")

    mismatched = players[players["name_mismatch"]]
    rows = []
    for _, r in mismatched.iterrows():
        rows.append([f"`{r['player_id']}`", r["registry_name"], r["bbb_name"]])
    add(
        f"Name harmonisation: **{_fmt_int(int(players['name_mismatch'].sum()))}** player ID has a "
        "different registry name and ball-by-ball name. Names are otherwise stable "
        "within each ID (0 IDs with multiple striker names, 0 with multiple bowler names)."
    )
    if rows:
        add("")
        add(_md_table(["player_id", "registry name", "ball-by-ball name"], rows))
    add("")

    # ------------------------------------------------------------------
    # 8. Assumptions
    # ------------------------------------------------------------------
    add("## 8. Assumptions (carried into every stage)")
    add("")
    n_ready = int(matches["analysis_ready"].sum())
    n_margin_checked = int(checks["stated_margin"].notna().sum())
    assumptions = [
        f"**Runs fields.** `runs` is runs off the bat. Delivery total = `runs + extras1_runs + extras_2_runs`. Validated by reconstructing {_fmt_int(n_margin_checked)} run-margin results in the analysis-ready set with zero mismatches.",
        "**No-balls.** `Overstep` and `other` are no-ball families: the delivery is illegal, the batter faces it and can score off it, and the bowler is charged the bat runs plus the extra. `other` rows behave exactly like `Overstep` (over_ball_num > 6, 1 penalty run, bat runs possible).",
        "**Wides.** A wide is not a ball faced and is charged entirely to the bowler. 40 wickets fall on wides (run out/stumping); these are wickets lost but not bowler wickets.",
        "**Byes and leg-byes.** Not charged to the bowler; they are team extras. One row (`match_id` 37099) is tagged `legbyes` with zero extra runs and one run off the bat; the additive formula still reconstructs the innings total.",
        "**Penalty.** The single `Penalty` row (match 16753, 5 runs) is not a delivery: no legal ball, no batter ball faced, no bowler charge. That match is also DLS-shortened and excluded.",
        "**Super overs.** Innings 3 and 4 are super overs. They are excluded entirely, and matches decided by a super over or a one-over eliminator are excluded from modelling (regulation innings were tied).",
        "**Scope.** IPL (`comp_name` matching `IPL YYYY`) plus `match_format == 'T20I'`. The two other T20 competitions (IDs 2670 and 3289) are excluded: the PRD scopes the data to IPL + T20I, and one of them contains players missing from `playing_eleven`.",
        f"**Analysis-ready match set.** In-scope, a winner exists, both regulation innings exist and are complete (all balls used, all out, or target reached), not tied, no super over, and not DLS/shortened (`first_inn_revised_overs`, `second_inn_revised_overs` and `revised_target` all null, plus a result-text DLS check). This leaves {_fmt_int(n_ready)} matches. The completeness rule catches 11 otherwise-unflagged rain-truncated games. Ball-level rows from excluded matches remain in the cleaned fact table but are flagged and are never used for modelling.",
        "**Wickets.** `is_wicket` counts every dismissal including run out, retire out and obstructing the field. Bowler wickets are restricted to Bowled, Caught, LBW, Stump and Hit Wicket. One retire-out row has no `dismissed_player_id`; it is counted as a team wicket but attributed to nobody.",
        "**Player names.** The canonical output name is `competition_team_player_mapping.player_name` (the player registry), falling back to the ball-by-ball name. Only one ID differs between the two sources.",
        "**Player IDs.** IDs are global across competitions and seasons in this pack; they are used as the join key and never re-derived from names.",
        "**Impact players.** `playing_eleven.is_impact` marks IPL impact players; they are included when they bat or bowl, with `batting_order` from the ball-by-ball file where the XI row is absent.",
        "**Dates.** `match_date` is a date, not a timestamp; seasons run 2022 to 2026. No external data is used.",
    ]
    for i, text in enumerate(assumptions, start=1):
        add(f"{i}. {text}")
    add("")

    # ------------------------------------------------------------------
    # 9. Open questions
    # ------------------------------------------------------------------
    add("## 9. Open questions (asked once, at the Stage 0 checkpoint)")
    add("")
    add(
        "1. **Competition scope.** Default is to exclude the two non-IPL T20 competitions "
        "(30 matches, IDs 2670 and 3289). Confirm this, or say if they should be included "
        "as an extra T20 pool."
    )
    add(
        "2. **Dropdown spelling.** For player ID 4458 the registry says `AHT Donald`, the "
        "ball-by-ball file says `Aneurin Donald`. Default is the registry name. Confirm if "
        "the Unstop dropdown uses the display name instead."
    )
    add("")

    # ------------------------------------------------------------------
    # 10. Files produced
    # ------------------------------------------------------------------
    add("## 10. Stage 0 artefacts")
    add("")
    add("| artefact | path |")
    add("|---|---|")
    add("| this audit | `outputs/tables/data_audit.md` |")
    add("| loaders and cleaning | `src/load_clean.py` |")
    add("| paths, seed and constants | `src/config.py` |")
    add("| unit tests | `tests/test_load_clean.py` |")
    add("")

    config.TABLE_DIR.mkdir(parents=True, exist_ok=True)
    out_path = config.TABLE_DIR / "data_audit.md"
    out_path.write_text("\n".join(lines), encoding="utf-8")

    # ------------------------------------------------------------------
    # Console summary
    # ------------------------------------------------------------------
    print("=" * 78)
    print("STAGE 0 DATA AUDIT")
    print("=" * 78)
    for name in ["ball_by_ball", "matches", "teams", "competitions", "playing_eleven", "competition_team_player_mapping"]:
        print(f"{name:38s} rows={len(raw[name]):>7,}  cols={raw[name].shape[1]:>2}")
    print("-" * 78)
    print(f"deliveries={len(bbb):,}  matches_with_balls={bbb['match_id'].nunique():,}  "
          f"super_over_innings={int(bbb['is_super_over'].sum()):,}")
    print(f"legal={int(bbb['is_legal'].sum()):,} ({100*bbb['is_legal'].mean():.2f}%)  "
          f"wides={int(bbb['is_wide'].sum()):,}  no-balls={int(bbb['is_noball'].sum()):,}")
    print(f"matches in scope={int(matches['in_scope'].sum()):,}  "
          f"analysis-ready={int(matches['analysis_ready'].sum()):,} "
          f"(IPL={int(ready['is_ipl'].sum()):,}, T20I={int((~ready['is_ipl']).sum()):,})")
    print("-" * 78)
    print("exclusion reasons:")
    print(matches.loc[~matches["analysis_ready"], "exclusion_reason"].value_counts().to_string())
    print("-" * 78)
    print(f"duplicate deliveries: {dupes}; duplicate delivery keys: {key_dupes}")
    print(f"runs-win margin mismatches: {int((~checks['margin_ok']).sum())} "
          f"of {int(checks['stated_margin'].notna().sum())}")
    print(f"target failures: {int((~checks['target_ok']).sum())}; "
          f"ball failures: {int((~checks['balls_ok']).sum())}; "
          f"wicket failures: {int((~checks['wickets_ok']).sum())}")
    print(f"name mismatches: {int(players['name_mismatch'].sum())}")
    print("-" * 78)
    print(f"WROTE {out_path}")
    print("=" * 78)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
